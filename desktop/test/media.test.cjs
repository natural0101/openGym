const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { createMedia } = require('../media.cjs')

test('public desktop cannot download third-party artwork or create a media folder', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'opengym-media-policy-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  let requests = 0
  t.mock.method(globalThis, 'fetch', async () => { requests++; throw Error('Unexpected network request') })
  const dir = path.join(root, 'media'), events = []
  const media = createMedia(dir, [{ kind: 'img', name: 'exercise.jpg' }], value => events.push(value))
  assert.deepEqual(await media.inspect(), { state: 'local-only', downloadsEnabled: false, completed: 0, total: 1, errors: 0 })
  await assert.rejects(media.start(), /не скачивает/)
  assert.equal(requests, 0)
  assert.equal(media.stop().state, 'local-only')
  await assert.rejects(fs.access(dir), { code: 'ENOENT' })
  assert.equal(events.length, 1)
})

test('existing local artwork remains available and byte-for-byte unchanged', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'opengym-media-cache-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  const dir = path.join(root, 'media')
  await fs.mkdir(path.join(dir, 'img'), { recursive: true })
  const original = Buffer.from('Existing personal local media remains intact.')
  const file = path.join(dir, 'img', 'exercise.jpg')
  await fs.writeFile(file, original)
  const media = createMedia(dir, [{ kind: 'img', name: 'exercise.jpg' }, { kind: 'gif', name: 'missing.gif' }], () => {})
  const result = await media.inspect()
  assert.equal(result.completed, 1)
  assert.equal(result.total, 2)
  assert.equal(result.downloadsEnabled, false)
  await assert.rejects(media.start())
  assert.deepEqual(await fs.readFile(file), original)
  assert.equal((await media.inspect()).completed, 1)
})
